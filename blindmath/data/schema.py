"""Record schema for the training corpus. Every record carries provenance (rule 2)."""
from __future__ import annotations

import json
from dataclasses import dataclass, asdict
from typing import Iterable, Iterator

# Curriculum stage (1..8) of each domain; see blindmath.training.curriculum.
LICENSE_SELF_GENERATED = "CC0-1.0 (self-generated by blindmath)"


@dataclass
class Record:
    domain: str          # e.g. "arithmetic", "number_theory"
    generator: str       # generator function that produced it
    source: str          # provenance, e.g. "synthetic:blindmath.data.generators.arithmetic"
    license: str         # license of the underlying content
    text: str            # the training text itself
    stage: int = 1       # curriculum stage 1..8
    kind: str = "computation"  # "computation" | "proof" | "definition" (rule 5)

    def to_json(self) -> str:
        return json.dumps(asdict(self), ensure_ascii=False)

    @staticmethod
    def from_json(line: str) -> "Record":
        return Record(**json.loads(line))


def write_jsonl(path: str, records: Iterable[Record]) -> int:
    n = 0
    with open(path, "w", encoding="utf-8") as f:
        for r in records:
            f.write(r.to_json() + "\n")
            n += 1
    return n


def read_jsonl(path: str) -> Iterator[Record]:
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                yield Record.from_json(line)
